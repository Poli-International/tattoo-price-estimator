export type SupportedLanguage = 'en' | 'fr' | 'it' | 'de' | 'es' | 'nl' | 'pt' | 'th';

export const SUPPORTED_LANGUAGES: readonly SupportedLanguage[] = ['en', 'fr', 'it', 'de', 'es', 'nl', 'pt', 'th'] as const;

export const LANGUAGE_OPTIONS: { code: SupportedLanguage; label: string }[] = [
  { code: 'en', label: 'English' },
  { code: 'fr', label: 'Français' },
  { code: 'it', label: 'Italiano' },
  { code: 'de', label: 'Deutsch' },
  { code: 'es', label: 'Español' },
  { code: 'nl', label: 'Nederlands' },
  { code: 'pt', label: 'Português' },
  { code: 'th', label: 'ไทย' },
];

export function resolveInitialLanguage(): SupportedLanguage {
  // 1. Saved choice in localStorage
  if (typeof window !== 'undefined') {
    try {
      const saved = localStorage.getItem('poli_language') || localStorage.getItem('language');
      if (saved && (SUPPORTED_LANGUAGES as readonly string[]).includes(saved)) {
        return saved as SupportedLanguage;
      }
    } catch (e) {}
  }

  // 2. document.documentElement.lang if it names one of the seven
  if (typeof document !== 'undefined' && document.documentElement && document.documentElement.lang) {
    const docLang = document.documentElement.lang.slice(0, 2).toLowerCase();
    if ((SUPPORTED_LANGUAGES as readonly string[]).includes(docLang)) {
      return docLang as SupportedLanguage;
    }
  }

  // 3. navigator.language by its first two letters
  if (typeof navigator !== 'undefined' && navigator.language) {
    const navLang = navigator.language.slice(0, 2).toLowerCase();
    if ((SUPPORTED_LANGUAGES as readonly string[]).includes(navLang)) {
      return navLang as SupportedLanguage;
    }
  }

  // 4. English fallback
  return 'en';
}

let currentLanguage: SupportedLanguage = resolveInitialLanguage();

// Apply initial language to document attribute immediately before first paint
if (typeof document !== 'undefined' && document.documentElement) {
  document.documentElement.lang = currentLanguage;
}

export function setLanguage(lang: SupportedLanguage): void {
  currentLanguage = lang;
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = lang;
  }
  // the page shell around the app (tabs, embed section) translates itself on this
  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('poli-language', { detail: lang }));
  }
}

export function getLanguage(): SupportedLanguage {
  return currentLanguage;
}

export const DICTIONARIES: Record<string, Record<string, string>> = {
  en: EN_DICTIONARY,
  fr: FR_DICTIONARY,
  it: IT_DICTIONARY,
  de: DE_DICTIONARY,
  es: ES_DICTIONARY,
  nl: NL_DICTIONARY,
  pt: PT_DICTIONARY,
  th: TH_DICTIONARY,
};

// Expose on window for runtime testing and external callers
if (typeof window !== 'undefined') {
  (window as any).setLanguage = setLanguage;
  (window as any).getLanguage = getLanguage;
  (window as any).DICTIONARIES = DICTIONARIES;
}

/** Groups thousands the way the interface language writes them (12,000 / 12.000 / 12 000).
 *  Only whole numbers of 1,000 and more: hours and counts stay plain ("0.8"), because the
 *  Studio CRM bridge reads them back from the page and would take "0,8" for 8. */
export function fmt(n: number): string {
  if (!Number.isInteger(n) || Math.abs(n) < 1000) return String(n);
  try {
    return n.toLocaleString(getLanguage());
  } catch {
    return String(n);
  }
}

export function t(key: string, params?: Record<string, string | number>): string {
  const lang = getLanguage();
  const dict = DICTIONARIES[lang] || EN_DICTIONARY;
  let text = dict[key] || EN_DICTIONARY[key];
  if (!text) {
    return key;
  }
  if (params) {
    Object.keys(params).forEach((paramKey) => {
      const regex = new RegExp(`\\{${paramKey}\\}`, 'g');
      const v = params[paramKey];
      text = text.replace(regex, typeof v === 'number' ? fmt(v) : String(v));
    });
  }
  return text;
}

